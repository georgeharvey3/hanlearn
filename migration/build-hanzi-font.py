"""Build the hanzi web font: the Arphic Kai faces that Hanzi Writer's strokes trace.

Hanzi Writer's stroke data comes from Make Me a Hanzi, which took its simplified
outlines from AR PL KaitiM GB and its traditional ones from AR PL UKai. Serving
the same two faces makes a printed character match the one the writer animates.

No device ships these fonts, so the app serves them. Each face is cut into
WOFF2 chunks with a `unicode-range`, ordered by how often the dictionary uses a
character, so a page downloads only the chunks that hold its characters.

Needs fonttools and brotli (`pip install fonttools brotli`) and the two fonts:
  Debian/Ubuntu: fonts-arphic-gkai00mp (gkai00mp.ttf), fonts-arphic-ukai (ukai.ttc)

Usage: python migration/build-hanzi-font.py <gkai00mp.ttf> <ukai.ttc>
"""

import json
import sys
from collections import Counter
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTCollection, TTFont

ROOT = Path(__file__).resolve().parent.parent
DICTIONARY = ROOT / 'web-client' / 'public' / 'dictionary.json'
CHENGYUS = ROOT / 'web-client' / 'src' / 'data' / 'chengyus.ts'
OUT_DIR = ROOT / 'web-client' / 'public' / 'fonts' / 'hanzi'
CSS = OUT_DIR / 'hanzi.css'

CHUNK_SIZE = 400


def is_hanzi(ch):
    cp = ord(ch)
    return 0x3400 <= cp <= 0x9FFF or 0xF900 <= cp <= 0xFAFF or 0x20000 <= cp <= 0x3FFFF


def character_counts():
    """Count each hanzi across the dictionary and the chengyu data."""
    counts = Counter()
    for entry in json.loads(DICTIONARY.read_text(encoding='utf-8')):
        counts.update(ch for ch in entry['simp'] + entry['trad'] if is_hanzi(ch))
    counts.update(ch for ch in CHENGYUS.read_text(encoding='utf-8') if is_hanzi(ch))
    return counts


def unicode_range(chars):
    """A `unicode-range` value that lists the characters, merging runs."""
    cps = sorted(ord(c) for c in chars)
    parts, start, prev = [], cps[0], cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        parts.append(f'U+{start:X}' if start == prev else f'U+{start:X}-{prev:X}')
        if cp is not None:
            start = prev = cp
    return ', '.join(parts)


def build_face(font_path, family, slug, chars):
    """Write the face's chunks and return their @font-face rules."""
    rules = []
    for i in range(0, len(chars), CHUNK_SIZE):
        chunk = chars[i:i + CHUNK_SIZE]
        options = subset.Options()
        options.flavor = 'woff2'
        options.layout_features = []
        options.name_IDs = [1, 2]
        options.hinting = False
        options.desubroutinize = True
        options.drop_tables += ['FFTM', 'mort']
        font = TTFont(font_path, fontNumber=0)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=[ord(c) for c in chunk])
        subsetter.subset(font)
        name = f'{slug}-{i // CHUNK_SIZE:03d}.woff2'
        subset.save_font(font, str(OUT_DIR / name), options)
        rules.append(
            '@font-face {\n'
            f"  font-family: '{family}';\n"
            f"  src: url('/fonts/hanzi/{name}') format('woff2');\n"
            '  font-display: swap;\n'
            f'  unicode-range: {unicode_range(chunk)};\n'
            '}\n'
        )
    return rules


def main(gkai_path, ukai_path):
    counts = character_counts()
    by_frequency = [ch for ch, _ in counts.most_common()]

    gkai = set(TTFont(gkai_path).getBestCmap())
    ukai = set(TTCollection(ukai_path).fonts[0].getBestCmap())

    # KaitiM GB covers GB2312; UKai takes every other character it has.
    gkai_chars = [c for c in by_frequency if ord(c) in gkai]
    ukai_chars = [c for c in by_frequency if ord(c) not in gkai and ord(c) in ukai]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob('*.woff2'):
        old.unlink()

    rules = build_face(gkai_path, 'HanLearn Kai', 'gkai', gkai_chars)
    rules += build_face(ukai_path, 'HanLearn Kai', 'ukai', ukai_chars)

    CSS.write_text(
        '/* Generated by migration/build-hanzi-font.py. Do not edit. */\n'
        '/* AR PL KaitiM GB and AR PL UKai, under the Arphic Public License (LICENSE.txt). */\n\n'
        + '\n'.join(rules),
        encoding='utf-8',
    )
    size = sum(p.stat().st_size for p in OUT_DIR.glob('*.woff2'))
    print(f'{len(gkai_chars)} KaitiM GB + {len(ukai_chars)} UKai characters, '
          f'{len(rules)} chunks, {size / 1e6:.1f} MB')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
